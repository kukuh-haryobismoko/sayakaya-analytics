def strip_title(md):
    """Drop the leading '# ...' title and the build stamp line; keep body."""
    lines = md.split('\n')
    while lines and (lines[0].startswith('# ') or not lines[0].strip()):
        lines.pop(0)
    while lines and (not lines[0].strip() or lines[0].startswith('Dibangun ') or lines[0].startswith('Run 2026')):
        lines.pop(0)
    return '\n'.join(lines).strip()

def demote(md):
    """Push headings one level down (nest under our structure) and drop source numbering."""
    md = re.sub(r'^(#{2,5}) \d+\. ', lambda m: m.group(1) + ' ', md, flags=re.M)
    return re.sub(r'^(#{2,5}) ', lambda m: '#' * (len(m.group(1)) + 1) + ' ', md, flags=re.M)

def insert_before_data_requests(md, extra):
    i = md.find('## Data requests')
    if i < 0:
        return md + '\n\n' + extra
    return md[:i] + extra + '\n\n' + md[i:]

